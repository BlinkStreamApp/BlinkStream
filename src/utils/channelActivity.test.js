import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { acquireChannelActivity, clearChannelActivity, recordChannelRedemption, recordConfirmedViewerRedemption, mergeRedemptionMessages, normalizeChannelRedemption } from './channelActivity'
const scope = { accountId: '1', account: 'alice', channelId: '2', channel: 'channel' }
const reward = { id: 'reward', title: 'Drink', cost: 100 }
const raw = { id: 'server-1', user: { id: '1', login: 'alice' }, reward, status: 'UNFULFILLED', user_input: 'Water', redeemed_at: '2026-11-06T18:00:00Z' }
let sockets
class Socket {
  readyState = 1
  constructor(url) { this.url = url; this.send = vi.fn(); this.close = vi.fn(); sockets.push(this) }
  message(value) { this.onmessage?.({ data: JSON.stringify(value) }) }
  welcome(error = '') { this.onopen(); const nonce = JSON.parse(this.send.mock.calls[0][0]).nonce; this.message({ type: 'RESPONSE', nonce, error }) }
  event(topic, data) { this.message({ type: 'MESSAGE', data: { topic, message: JSON.stringify(data) } }) }
}
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(new Date(raw.redeemed_at)); sockets = []; vi.stubGlobal('WebSocket', Socket) })
afterEach(() => { clearChannelActivity('1'); clearChannelActivity('3'); vi.useRealTimers(); vi.unstubAllGlobals() })
it('shows a confirmed local receipt immediately without inventing queue fulfillment and reconciles its server ID', () => {
  const feed = acquireChannelActivity(scope)
  expect(recordConfirmedViewerRedemption(scope, reward, 'a'.repeat(32), ' Water ')).toBe(true)
  expect(feed.snapshot().redemptions[0]).toMatchObject({ status: 'CONFIRMED', manageable: false, source: 'local-confirmed' })
  const before = mergeRedemptionMessages([], feed.snapshot().redemptions)
  expect(before[0]).toMatchObject({ isReward: true, custom_reward_id: 'reward', message: '', channel: 'channel' })
  recordChannelRedemption(scope, raw, 'public')
  expect(feed.snapshot().redemptions).toHaveLength(1)
  expect(feed.snapshot().redemptions[0]).toMatchObject({ id: 'server-1', status: 'UNFULFILLED', localRequestId: 'a'.repeat(32) })
  expect(mergeRedemptionMessages(before, feed.snapshot().redemptions)).toHaveLength(1)
  feed.release()
})
it('keeps two deliberate identical purchases distinct while deduplicating repeated public/EventSub frames', () => {
  const feed = acquireChannelActivity(scope)
  recordConfirmedViewerRedemption(scope, reward, 'a'.repeat(32), 'Water')
  recordConfirmedViewerRedemption(scope, reward, 'b'.repeat(32), 'Water')
  recordChannelRedemption(scope, raw, 'public')
  recordChannelRedemption(scope, { ...raw, id: 'server-2' }, 'public')
  recordChannelRedemption(scope, raw, 'eventsub')
  expect(feed.snapshot().redemptions).toHaveLength(2)
  expect(new Set(feed.snapshot().redemptions.map(r => r.localRequestId)).size).toBe(2)
  feed.release()
})
it('shares one credential-free connection, accepts exact topics only and stops after the last owner', () => {
  const first = acquireChannelActivity(scope, true), second = acquireChannelActivity(scope, true)
  expect(sockets).toHaveLength(1)
  expect(sockets[0].url).toBe('wss://pubsub-edge.twitch.tv')
  sockets[0].welcome()
  const listen = JSON.parse(sockets[0].send.mock.calls[0][0])
  expect(listen.data.topics).toEqual(['community-points-channel-v1.2', 'predictions-channel-v1.2', 'polls.2'])
  expect(listen.data).not.toHaveProperty('auth_token')
  sockets[0].event('community-points-channel-v1.9', { type: 'reward-redeemed', data: { redemption: raw } })
  expect(first.snapshot().redemptions).toHaveLength(0)
  sockets[0].event('community-points-channel-v1.2', { type: 'reward-redeemed', data: { redemption: raw } })
  expect(first.snapshot().redemptions).toHaveLength(1)
  first.release(); expect(sockets[0].close).not.toHaveBeenCalled()
  second.release(); expect(sockets[0].close).toHaveBeenCalledOnce()
  expect(vi.getTimerCount()).toBe(0)
})
it('reports refused subscriptions without retrying and reconnects a network failure with bounded backoff', async () => {
  const feed = acquireChannelActivity(scope, true)
  sockets[0].welcome('ERR_BADAUTH')
  expect(feed.snapshot().state).toBe('unavailable')
  await vi.advanceTimersByTimeAsync(60000)
  expect(sockets).toHaveLength(1)
  feed.release()
  const retrying = acquireChannelActivity(scope, true)
  sockets[1].onclose()
  await vi.advanceTimersByTimeAsync(1000)
  expect(sockets).toHaveLength(3)
  retrying.release()
  expect(vi.getTimerCount()).toBe(0)
})
it('updates public polls/predictions without claiming creator privileges and clears account data', () => {
  const first = acquireChannelActivity(scope, true)
  const other = acquireChannelActivity({ ...scope, accountId: '3' })
  sockets[0].welcome()
  sockets[0].event('predictions-channel-v1.2', { type: 'event-created', data: { event: { id: 'p1', title: 'Win?', status: 'ACTIVE', outcomes: [{ id: 'o1', title: 'Yes', total_points: 50 }] } } })
  sockets[0].event('polls.2', { type: 'POLL_CREATE', data: { poll: { poll_id: 'poll1', title: 'Drink?', status: 'ACTIVE', choices: [{ choice_id: 'c1', title: 'Water', votes: { total: 3 } }] } } })
  expect(first.snapshot().predictions[0].outcomes[0].channel_points).toBe(50)
  expect(first.snapshot().polls[0].choices[0].votes).toBe(3)
  expect(other.snapshot().polls).toHaveLength(0)
  clearChannelActivity('1')
  const fresh = acquireChannelActivity(scope)
  expect(fresh.snapshot().predictions).toHaveLength(0)
  first.release(); other.release(); fresh.release()
})
it('rejects foreign channels, malformed costs and unconfirmed request IDs; bounds received notices', () => {
  expect(normalizeChannelRedemption({ ...raw, channel_id: '9' }, scope)).toBeNull()
  expect(normalizeChannelRedemption({ ...raw, reward: { ...reward, cost: -1 } }, scope)).toBeNull()
  expect(recordConfirmedViewerRedemption(scope, reward, 'not-a-confirmed-request', '')).toBe(false)
  const feed = acquireChannelActivity(scope)
  for (let i = 0; i < 210; i++) recordChannelRedemption(scope, { ...raw, id: `event-${i}` }, 'public')
  expect(feed.snapshot().redemptions).toHaveLength(200)
  feed.release()
})
it('joins a matching IRC reward once without coalescing distinct purchases or restoring deleted input', () => {
  const rd = normalizeChannelRedemption(raw, scope)
  const irc = { id: 'irc1', custom_reward_id: 'reward', user_id: '1', message: 'Water', timestamp: Date.parse(raw.redeemed_at) }
  const first = mergeRedemptionMessages([irc], [rd])
  expect(first).toHaveLength(1)
  expect(first[0]).toMatchObject({ id: 'irc1', redemption_id: 'server-1', message: 'Water' })
  expect(mergeRedemptionMessages([irc], [rd])[0]).toBe(first[0])
  expect(mergeRedemptionMessages([irc], [rd, { ...rd, id: 'server-2' }])).toHaveLength(2)
  expect(mergeRedemptionMessages([], [rd])[0].message).toBe('')
})

it.each(['onclose', 'onerror', 'timeout', 'RECONNECT'])('retains observations and a sticky gap after confirmed %s, retries and new events', async reason => {
  const feed = acquireChannelActivity(scope, true)
  expect(feed.snapshot().possibleGap).toBe(false)
  sockets[0].welcome()
  sockets[0].event('polls.2', { data: { poll: { id: 'before', title: 'Before' } } })
  const oldMessage = sockets[0].onmessage, oldClose = sockets[0].onclose
  if (reason === 'timeout') await vi.advanceTimersByTimeAsync(45000)
  else if (reason === 'RECONNECT') sockets[0].message({ type: 'RECONNECT' })
  else sockets[0][reason]()
  expect(feed.snapshot()).toMatchObject({ state: 'reconnecting', possibleGap: true })
  expect(feed.snapshot().polls[0].id).toBe('before')
  await vi.advanceTimersByTimeAsync(1000)
  oldClose(); oldMessage({ data: JSON.stringify({ type: 'RECONNECT' }) })
  sockets[1].welcome()
  sockets[1].event('polls.2', { data: { poll: { id: 'after' } } })
  expect(feed.snapshot()).toMatchObject({ state: 'connected', possibleGap: true })
  expect(feed.snapshot().polls).toHaveLength(2)
  sockets[1].onerror()
  expect(feed.snapshot().possibleGap).toBe(true)
  const unrelated = acquireChannelActivity({ ...scope, accountId: '3' }, true)
  expect(unrelated.snapshot().possibleGap).toBe(false)
  unrelated.release(); feed.release()
})
it('does not let early PONG extend the LISTEN watchdog or claim a startup gap', async () => {
  const feed = acquireChannelActivity(scope, true)
  sockets[0].onopen()
  await vi.advanceTimersByTimeAsync(9000)
  sockets[0].message({ type: 'PONG' })
  await vi.advanceTimersByTimeAsync(1000)
  expect(feed.snapshot()).toMatchObject({ state: 'reconnecting', possibleGap: false })
  await vi.advanceTimersByTimeAsync(1000)
  sockets[1].welcome()
  await vi.advanceTimersByTimeAsync(9000)
  expect(feed.snapshot().state).toBe('connected')
  feed.release()
})
it('marks continuity only at the final confirmed owner release and retains local receipts on reacquire', () => {
  const a = acquireChannelActivity(scope, true), b = acquireChannelActivity(scope, true)
  sockets[0].welcome()
  recordConfirmedViewerRedemption(scope, reward, 'c'.repeat(32), '')
  a.release()
  expect(b.snapshot().possibleGap).toBe(false)
  b.release()
  const again = acquireChannelActivity(scope, true)
  expect(again.snapshot().possibleGap).toBe(true)
  expect(again.snapshot().redemptions[0].source).toBe('local-confirmed')
  again.release()
})
it('keeps local-only/disabled observers and new channels free of inherited gaps', () => {
  const local = acquireChannelActivity(scope)
  local.release()
  const again = acquireChannelActivity(scope)
  const channel = acquireChannelActivity({ ...scope, channelId: '99' }, true)
  expect(again.snapshot().possibleGap).toBe(false)
  expect(channel.snapshot().possibleGap).toBe(false)
  expect(sockets).toHaveLength(1)
  again.release(); channel.release()
})
